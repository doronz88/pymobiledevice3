"""
Regenerate ``pymobiledevice3/remote/ddi_services.py`` from the DeveloperDiskImage repository.

Mounts every personalized iOS DDI in the history of a https://github.com/doronz88/DeveloperDiskImage
checkout and records the RSD services its launch daemons declare (``RemoteServices`` in
``Library/LaunchDaemons/*.plist``). macOS only (``hdiutil``). Run it after bumping
``LATEST_DDI_BUILD_ID``::

    python misc/ddi_services.py ~/dev/DeveloperDiskImage
"""

import plistlib
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Optional

IMAGE = "PersonalizedImages/Xcode_iOS_DDI_Personalized/Image.dmg"
OUTPUT = Path(__file__).parent.parent / "pymobiledevice3" / "remote" / "ddi_services.py"

HEADER = """\"\"\"
Which RSD services the DeveloperDiskImage provides, and in which builds.

These services are not part of iOS: launch daemons inside the mounted DeveloperDiskImage declare
them, so the device offers one only while a DDI that includes it is mounted.

The data is generated by ``misc/ddi_services.py`` from the history of the DeveloperDiskImage
repository -- do not edit it by hand.
\"\"\"

import re
from typing import Optional

"""

FOOTER = """

def _train(build: str) -> Optional[tuple[int, str]]:
    \"\"\"The release train of a build id (``27B52`` -> ``(27, "B")``), which orders builds of different trains.\"\"\"
    match = re.match(r"(\\d+)([A-Z])\\d", build)
    return (int(match.group(1)), match.group(2)) if match else None


def _position(build: str) -> Optional[float]:
    \"\"\"
    Where a build falls among `DDI_BUILDS`: its index, or halfway between two indices for a build
    that is not one of them but whose train puts it between the two. ``None`` when that cannot be
    told -- an unparsable build id, or one sharing its train with a known build, since a seed
    (``27A5194q``) and a release (``27A300``) of one train do not order by their numbers.
    \"\"\"
    if build in DDI_BUILDS:
        return float(DDI_BUILDS.index(build))
    train = _train(build)
    known = [_train(known_build) for known_build in DDI_BUILDS]
    if train is None or train in known:
        return None
    return sum(known_train is not None and known_train < train for known_train in known) - 0.5


def ddi_includes(service_name: str, build: str) -> Optional[bool]:
    \"\"\"
    Whether the DeveloperDiskImage of a given build provides a service.

    Also answers for builds that are not in `DDI_BUILDS`, by where their release train puts them:
    older than the last known build without the service, or newer than the first one with it.

    :param service_name: an RSD service name the DDI provides (a key of `DDI_SERVICES`).
    :param build: build id of a DeveloperDiskImage, e.g. ``27B52``.
    :returns: ``None`` when there is no telling, e.g. for a build between the last known one
        without the service and the first known one with it.
    \"\"\"
    position = _position(build)
    if position is None:
        return None
    first_build, last_build = DDI_SERVICES[service_name]
    first = DDI_BUILDS.index(first_build)
    if last_build is None:
        if position >= first:
            return True
        return False if position <= first - 1 else None
    last = DDI_BUILDS.index(last_build)
    if first <= position <= last:
        return True
    # Strictly between the last known build without the service and the first one with it (or
    # the other way round past `last`), there is no telling
    if position <= first - 1 or position >= last + 1:
        return False
    return None
"""


def remote_services(repo: Path, commit: str) -> tuple[str, set[str]]:
    """Return the build id of the DDI at ``commit`` and the RSD services its launch daemons declare."""
    with tempfile.TemporaryDirectory() as tmp:
        dmg = Path(tmp) / "Image.dmg"
        mount_point = Path(tmp) / "mnt"
        mount_point.mkdir()
        dmg.write_bytes(
            subprocess.run(
                ["git", "-C", str(repo), "show", f"{commit}:{IMAGE}"], capture_output=True, check=True
            ).stdout
        )
        subprocess.run(
            ["hdiutil", "attach", "-nobrowse", "-readonly", "-mountpoint", str(mount_point), str(dmg)],
            capture_output=True,
            check=True,
        )
        try:
            build = plistlib.loads((mount_point / "version.plist").read_bytes())["ProductBuildVersion"]
            services: set[str] = set()
            for plist in (mount_point / "Library" / "LaunchDaemons").glob("*.plist"):
                services |= set(plistlib.loads(plist.read_bytes()).get("RemoteServices") or {})
        finally:
            subprocess.run(["hdiutil", "detach", str(mount_point)], capture_output=True, check=False)
    return build, services


def main() -> None:
    repo = Path(sys.argv[1])
    commits = subprocess.run(
        ["git", "-C", str(repo), "log", "--reverse", "--format=%H", "--", IMAGE],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()

    table: dict[str, set[str]] = {}
    for commit in commits:
        build, services = remote_services(repo, commit)
        table.setdefault(build, services)
    builds = list(table)

    spans: dict[str, tuple[str, Optional[str]]] = {}
    for name in sorted(set().union(*table.values())):
        including = [name in table[build] for build in builds]
        first = including.index(True)
        last = len(builds) - 1 - including[::-1].index(True)
        # A (first, last) span cannot say that a service was dropped and brought back
        if not all(including[first : last + 1]):
            raise SystemExit(f"{name} is missing from a build between {builds[first]} and {builds[last]}")
        spans[name] = (builds[first], None if last == len(builds) - 1 else builds[last])

    lines = [HEADER]
    lines.append("#: Builds of the DeveloperDiskImage the table was generated from, oldest first.\n")
    lines.append("DDI_BUILDS = [\n" + "".join(f'    "{build}",\n' for build in builds) + "]\n\n")
    lines.append(
        "#: RSD service name -> the first of `DDI_BUILDS` whose DeveloperDiskImage provides it, and the last\n"
    )
    lines.append(
        "#: one that does when a newer DDI dropped it: ``None`` for a service the newest DDI still provides.\n"
    )
    lines.append("DDI_SERVICES: dict[str, tuple[str, Optional[str]]] = {\n")
    for name, (first_build, last_build) in spans.items():
        last_literal = "None" if last_build is None else f'"{last_build}"'
        lines.append(f'    "{name}": ("{first_build}", {last_literal}),\n')
    lines.append("}\n")
    lines.append(FOOTER)
    OUTPUT.write_text("".join(lines))


if __name__ == "__main__":
    main()
