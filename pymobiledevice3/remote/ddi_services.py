"""
Which RSD services the DeveloperDiskImage provides, and in which builds.

These services are not part of iOS: launch daemons inside the mounted DeveloperDiskImage declare
them, so the device offers one only while a DDI that includes it is mounted.

The data is generated by ``misc/ddi_services.py`` from the history of the DeveloperDiskImage
repository -- do not edit it by hand.
"""

import re
from typing import Optional

#: Builds of the DeveloperDiskImage the table was generated from, oldest first.
DDI_BUILDS = [
    "15A5160n",
    "15A240d",
    "15F31c",
    "16A242d",
    "16B40",
    "16E5121h",
    "17A324",
    "17B5045g",
    "17E5179g",
    "27A5194q",
    "27A5228h",
    "27B52",
]

#: RSD service name -> the first of `DDI_BUILDS` whose DeveloperDiskImage provides it, and the last
#: one that does when a newer DDI dropped it: ``None`` for a service the newest DDI still provides.
DDI_SERVICES: dict[str, tuple[str, Optional[str]]] = {
    "com.apple.coredevice.appservice": ("15A5160n", None),
    "com.apple.coredevice.configuration": ("27A5194q", None),
    "com.apple.coredevice.debugserverproxy": ("16E5121h", None),
    "com.apple.coredevice.devicecontrol": ("27A5194q", None),
    "com.apple.coredevice.deviceinfo": ("15A5160n", None),
    "com.apple.coredevice.diagnosticsservice": ("15A5160n", None),
    "com.apple.coredevice.displayservice": ("27A5194q", None),
    "com.apple.coredevice.fileservice.control": ("15A5160n", None),
    "com.apple.coredevice.fileservice.data": ("15A5160n", None),
    "com.apple.coredevice.hid.indigo": ("27A5194q", None),
    "com.apple.coredevice.hid.universalhid": ("27A5194q", None),
    "com.apple.coredevice.hid.universalhidservice": ("27A5194q", None),
    "com.apple.coredevice.iconservice": ("17E5179g", None),
    "com.apple.coredevice.locationservice": ("27A5194q", None),
    "com.apple.coredevice.openstdiosocket": ("15A5160n", None),
    "com.apple.coredevice.pasteboardservice": ("27A5194q", None),
    "com.apple.coredevice.screencaptureservice": ("27A5194q", None),
    "com.apple.dt.testmanagerd.remote": ("15A5160n", None),
    "com.apple.dt.testmanagerd.remote.automation": ("15A5160n", None),
    "com.apple.gputools.remote.agent": ("15A5160n", None),
    "com.apple.internal.dt.remote.debugproxy": ("15A5160n", None),
}


def _train(build: str) -> Optional[tuple[int, str]]:
    """The release train of a build id (``27B52`` -> ``(27, "B")``), which orders builds of different trains."""
    match = re.match(r"(\d+)([A-Z])\d", build)
    return (int(match.group(1)), match.group(2)) if match else None


def _position(build: str) -> Optional[float]:
    """
    Where a build falls among `DDI_BUILDS`: its index, or halfway between two indices for a build
    that is not one of them but whose train puts it between the two. ``None`` when that cannot be
    told -- an unparsable build id, or one sharing its train with a known build, since a seed
    (``27A5194q``) and a release (``27A300``) of one train do not order by their numbers.
    """
    if build in DDI_BUILDS:
        return float(DDI_BUILDS.index(build))
    train = _train(build)
    known = [_train(known_build) for known_build in DDI_BUILDS]
    if train is None or train in known:
        return None
    return sum(known_train is not None and known_train < train for known_train in known) - 0.5


def ddi_includes(service_name: str, build: str) -> Optional[bool]:
    """
    Whether the DeveloperDiskImage of a given build provides a service.

    Also answers for builds that are not in `DDI_BUILDS`, by where their release train puts them:
    older than the last known build without the service, or newer than the first one with it.

    :param service_name: an RSD service name the DDI provides (a key of `DDI_SERVICES`).
    :param build: build id of a DeveloperDiskImage, e.g. ``27B52``.
    :returns: ``None`` when there is no telling, e.g. for a build between the last known one
        without the service and the first known one with it.
    """
    position = _position(build)
    if position is None:
        return None
    first_build, last_build = DDI_SERVICES[service_name]
    first = DDI_BUILDS.index(first_build)
    if last_build is None:
        if position >= first:
            return True
        return False if position <= first - 1 else None
    last = DDI_BUILDS.index(last_build)
    if first <= position <= last:
        return True
    # Strictly between the last known build without the service and the first one with it (or
    # the other way round past `last`), there is no telling
    if position <= first - 1 or position >= last + 1:
        return False
    return None
